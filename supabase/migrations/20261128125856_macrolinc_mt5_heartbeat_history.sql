create table if not exists public.macrolinc_mt5_heartbeat_history (
  id bigint generated by default as identity primary key,
  account_key text not null check (account_key ~ '^[a-f0-9]{64}$'),
  login text not null,
  server text not null,
  broker text,
  account_equity numeric(20,8) not null check (account_equity > 0),
  account_balance numeric(20,8) not null check (account_balance > 0),
  daily_closed_trades integer not null check (daily_closed_trades >= 0),
  daily_losses integer not null check (daily_losses >= 0 and daily_losses <= daily_closed_trades),
  live_broker_spread numeric(20,10) check (live_broker_spread is null or live_broker_spread >= 0),
  spread_symbol text,
  open_currency_legs jsonb,
  daily_stats_time_basis text not null check (daily_stats_time_basis = 'BROKER_SERVER_DAY'),
  timestamp_utc timestamptz not null,
  received_at timestamptz not null default now(),
  unique (account_key, timestamp_utc)
);

create index if not exists macrolinc_mt5_heartbeat_account_time_idx
  on public.macrolinc_mt5_heartbeat_history (account_key, timestamp_utc desc);

create index if not exists macrolinc_mt5_heartbeat_received_idx
  on public.macrolinc_mt5_heartbeat_history (received_at desc);

alter table public.macrolinc_mt5_heartbeat_history enable row level security;
revoke all on table public.macrolinc_mt5_heartbeat_history from public, anon, authenticated;
grant select, insert on table public.macrolinc_mt5_heartbeat_history to service_role;
grant usage, select on sequence public.macrolinc_mt5_heartbeat_history_id_seq to service_role;

create or replace function public.get_macrolinc_rolling_7d_drawdown(p_account_key text)
returns table (
  drawdown_pct double precision,
  sample_count bigint,
  first_observed_at timestamptz,
  last_observed_at timestamptz,
  max_gap_seconds double precision,
  coverage_complete boolean
)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  with ordered as (
    select
      timestamp_utc,
      account_equity::double precision as equity,
      max(account_equity::double precision) over (
        order by timestamp_utc
        rows between unbounded preceding and current row
      ) as running_peak,
      lag(timestamp_utc) over (order by timestamp_utc) as previous_timestamp
    from public.macrolinc_mt5_heartbeat_history
    where account_key = p_account_key
      and timestamp_utc >= now() - interval '7 days'
      and timestamp_utc <= now() + interval '30 seconds'
  ),
  stats as (
    select
      count(*) as n,
      min(timestamp_utc) as first_at,
      max(timestamp_utc) as last_at,
      max(extract(epoch from (timestamp_utc - previous_timestamp)))::double precision as max_gap,
      max(case when running_peak > 0 then ((running_peak - equity) / running_peak) * 100 else 100 end)::double precision as max_dd
    from ordered
  )
  select
    case
      when n >= 1000
       and first_at <= now() - interval '6 days 23 hours'
       and last_at >= now() - interval '120 seconds'
       and coalesce(max_gap, 999999) <= 600
      then -coalesce(max_dd, 0)
      else null
    end as drawdown_pct,
    n as sample_count,
    first_at as first_observed_at,
    last_at as last_observed_at,
    max_gap as max_gap_seconds,
    (
      n >= 1000
      and first_at <= now() - interval '6 days 23 hours'
      and last_at >= now() - interval '120 seconds'
      and coalesce(max_gap, 999999) <= 600
    ) as coverage_complete
  from stats;
$$;

revoke all on function public.get_macrolinc_rolling_7d_drawdown(text) from public, anon, authenticated;
grant execute on function public.get_macrolinc_rolling_7d_drawdown(text) to service_role;

comment on table public.macrolinc_mt5_heartbeat_history is
  'Append-only, server-received MT5 account heartbeat history. A rolling 7-day drawdown is unavailable until a full, sufficiently dense 7-day equity history exists.';
comment on function public.get_macrolinc_rolling_7d_drawdown(text) is
  'Returns negative maximum peak-to-trough equity drawdown over a fully observed 7-day window. Null means coverage is insufficient; this is not cash-flow adjusted.';
